using System.Security.Cryptography;
using System.Security.Cryptography.X509Certificates;
using Microsoft.Extensions.Logging;
using WorldPinball.Application.Security.CA;

namespace WorldPinball.Infrastructure.Security.CA;

public sealed class StepCaCertificateAuthorityService(
    ILogger<StepCaCertificateAuthorityService> logger,
    TimeProvider timeProvider
) : ICertificateAuthorityService
{
    // Intermediate CA signing key pair (in-memory authority key for dev / testing)
    private static readonly ECDsa CaSigningKey = ECDsa.Create(ECCurve.NamedCurves.nistP256);

    public Task<IssuedCertificate> IssueDeviceCertificateAsync(
        Guid machineId,
        string deviceSerialNumber,
        string publicKeyPem,
        CancellationToken ct = default)
    {
        var now = timeProvider.GetUtcNow().UtcDateTime;
        var notBefore = now.AddMinutes(-5); // Clock skew tolerance
        var notAfter = now.AddYears(1);     // Certificate validity: 1 year

        // 1. Import device ECDSA public key generated by TPM
        using var devicePublicKey = ECDsa.Create();
        devicePublicKey.ImportFromPem(publicKeyPem);

        // 2. Build X.509 Certificate Signing Request (CSR) with the device's public key
        var subjectDn = $"CN={deviceSerialNumber}, O=WorldPinball, OU=Devices";
        var request = new CertificateRequest(
            new X500DistinguishedName(subjectDn),
            devicePublicKey,
            HashAlgorithmName.SHA256);

        // 3. Configure standard X.509 extensions for client authentication
        // Basic Constraints: End-entity leaf certificate (cannot act as a CA)
        request.CertificateExtensions.Add(
            new X509BasicConstraintsExtension(
                certificateAuthority: false,
                hasPathLengthConstraint: false,
                pathLengthConstraint: 0,
                critical: true));

        // Key Usage: Digital Signature and Key Agreement
        request.CertificateExtensions.Add(
            new X509KeyUsageExtension(
                X509KeyUsageFlags.DigitalSignature | X509KeyUsageFlags.KeyAgreement,
                critical: true));

        // Enhanced Key Usage (EKU): TLS Web Client Authentication (RFC 5280 - 1.3.6.1.5.5.7.3.2)
        request.CertificateExtensions.Add(
            new X509EnhancedKeyUsageExtension(
                new OidCollection { new("1.3.6.1.5.5.7.3.2") },
                critical: false));

        var sanBuilder = new SubjectAlternativeNameBuilder();
        sanBuilder.AddUri(new Uri($"urn:pinball:machine:{machineId}"));
        request.CertificateExtensions.Add(sanBuilder.Build());

        
        
        // 4. Generate random positive serial number on the stack (Safe Span - 0 GC allocation)
        Span<byte> serialNumberBytes = stackalloc byte[16];
        RandomNumberGenerator.Fill(serialNumberBytes);
        serialNumberBytes[0] &= 0x7F; // Ensure positive big-endian integer for X.509 standard
        
        // 5. Create signed leaf certificate using the CA's private signing key
        const string issuerDn = "CN=WorldPinball Intermediate CA, O=WorldPinball Internal CA";
        using var cert = request.Create(
            new X500DistinguishedName(issuerDn),
            X509SignatureGenerator.CreateForECDsa(CaSigningKey),
            notBefore,
            notAfter,
            serialNumberBytes);

        var certPem = cert.ExportCertificatePem();
        var certSerialNumber = Convert.ToHexString(serialNumberBytes).ToLowerInvariant();
        var thumbprint = Convert.ToHexString(SHA256.HashData(cert.RawData)).ToLowerInvariant();

        logger.LogInformation(
            "Issued X.509 certificate for device serial {DeviceSerialNumber} (CertSerial: {CertSerial})",
            deviceSerialNumber,
            certSerialNumber);

        var issued = new IssuedCertificate(
            CertPem: certPem,
            SerialNumber: certSerialNumber,
            MachineId: machineId,
            ThumbprintSha256: thumbprint,
            SubjectDn: subjectDn,
            IssuerDn: issuerDn,
            NotBeforeUtc: notBefore,
            NotAfterUtc: notAfter
        );

        return Task.FromResult(issued);
    }
}
